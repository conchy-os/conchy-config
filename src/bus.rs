use anyhow::{Context, Result};
use tracing::info;
use zbus::object_server::SignalEmitter;
use zbus::{interface, proxy, Connection};

use crate::store::ConfigStore;

pub const DBUS_SERVICE_NAME: &str = "org.conchy.Config";
pub const DBUS_OBJECT_PATH: &str = "/org/conchy/Config";

/// D-Bus Service Implementation for org.conchy.Config
pub struct ConfigServer {
    store: ConfigStore,
}

impl ConfigServer {
    pub fn new(store: ConfigStore) -> Self {
        Self { store }
    }

    pub fn store(&self) -> &ConfigStore {
        &self.store
    }
}

#[interface(name = "org.conchy.Config")]
impl ConfigServer {
    /// Reads a property value by channel and key (e.g. channel="wm", key="layout.gaps")
    async fn get(&self, channel: String, key: String) -> zbus::fdo::Result<String> {
        match self.store.get(&channel, &key) {
            Ok(Some(val)) => Ok(val),
            Ok(None) => Err(zbus::fdo::Error::UnknownProperty(format!(
                "Property '{}' not found in channel '{}'",
                key, channel
            ))),
            Err(e) => Err(zbus::fdo::Error::Failed(e.to_string())),
        }
    }

    /// Sets a property value and broadcasts PropertyChanged signal
    async fn set(
        &self,
        #[zbus(signal_emitter)] emitter: SignalEmitter<'_>,
        channel: String,
        key: String,
        value: String,
    ) -> zbus::fdo::Result<()> {
        self.store
            .set(&channel, &key, &value)
            .map_err(|e| zbus::fdo::Error::Failed(e.to_string()))?;

        info!("D-Bus Set [{}] {} = {}", channel, key, value);

        Self::property_changed(&emitter, &channel, &key, &value)
            .await
            .map_err(|e| zbus::fdo::Error::Failed(e.to_string()))?;

        Ok(())
    }

    /// Lists all properties defined in a channel
    async fn list(&self, channel: String) -> zbus::fdo::Result<Vec<(String, String)>> {
        self.store
            .list(&channel)
            .map_err(|e| zbus::fdo::Error::Failed(e.to_string()))
    }

    /// Broadcast signal emitted whenever a setting is updated (either via D-Bus or file edit)
    #[zbus(signal)]
    pub async fn property_changed(
        emitter: &SignalEmitter<'_>,
        channel: &str,
        key: &str,
        value: &str,
    ) -> zbus::Result<()>;
}

/// Strongly-typed client proxy generated by zbus (will generate ConfigProxy)
#[proxy(
    interface = "org.conchy.Config",
    default_service = "org.conchy.Config",
    default_path = "/org/conchy/Config"
)]
pub trait Config {
    fn get(&self, channel: &str, key: &str) -> zbus::Result<String>;
    fn set(&self, channel: &str, key: &str, value: &str) -> zbus::Result<()>;
    fn list(&self, channel: &str) -> zbus::Result<Vec<(String, String)>>;

    #[zbus(signal)]
    fn property_changed(&self, channel: String, key: String, value: String) -> zbus::Result<()>;
}

/// High-level client for applications (like conchy-shell, conchy-wm, conchy-settings)
pub struct ConfigClient {
    proxy: ConfigProxy<'static>,
}

impl ConfigClient {
    pub async fn new(connection: &Connection) -> Result<Self> {
        let proxy = ConfigProxy::new(connection)
            .await
            .context("Failed to connect to org.conchy.Config D-Bus service")?;
        Ok(Self { proxy })
    }

    pub async fn get(&self, channel: &str, key: &str) -> Result<String> {
        self.proxy
            .get(channel, key)
            .await
            .with_context(|| format!("Failed to get [{}] {}", channel, key))
    }

    pub async fn set(&self, channel: &str, key: &str, value: &str) -> Result<()> {
        self.proxy
            .set(channel, key, value)
            .await
            .with_context(|| format!("Failed to set [{}] {} = {}", channel, key, value))
    }

    pub async fn list(&self, channel: &str) -> Result<Vec<(String, String)>> {
        self.proxy
            .list(channel)
            .await
            .with_context(|| format!("Failed to list channel [{}]", channel))
    }

    pub async fn receive_property_changed(&self) -> Result<PropertyChangedStream> {
        self.proxy
            .receive_property_changed()
            .await
            .context("Failed to subscribe to PropertyChanged signals")
    }
}
